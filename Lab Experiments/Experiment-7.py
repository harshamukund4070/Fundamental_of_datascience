import pandas as pd
import matplotlib.pyplot as plt
data=pd.read_csv("order_data.csv")
orders=data.groupby("CustomerID").size()
average=data.groupby("Product")["Quantity"].mean()
earliest=data["OrderDate"].min()
latest=data["OrderDate"].max()
print(orders)
print(average)
print(earliest)
print(latest)
orders.plot(kind="bar")
plt.title("Orders by Customer")
plt.xlabel("Customer")
plt.ylabel("Orders")
plt.show()
average.plot(kind="bar")
plt.title("Average Quantity by Product")
plt.xlabel("Product")
plt.ylabel("Average Quantity")
plt.show()