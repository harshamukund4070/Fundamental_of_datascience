import pandas as pd
import matplotlib.pyplot as plt
data=pd.read_csv("student_study.csv")
correlation=data["StudyHours"].corr(data["ExamScore"])
print(correlation)
plt.figure(figsize=(6,4))
plt.scatter(data["StudyHours"],data["ExamScore"])
plt.title("Study Hours vs Exam Score")
plt.xlabel("Study Hours")
plt.ylabel("Exam Score")
plt.grid(True)
plt.show()
plt.figure(figsize=(6,4))
plt.plot(data["StudyHours"],data["ExamScore"],marker="o")
plt.title("Study Hours and Exam Score")
plt.xlabel("Study Hours")
plt.ylabel("Exam Score")
plt.grid(True)
plt.show()