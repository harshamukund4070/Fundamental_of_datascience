import pandas as pd
import matplotlib.pyplot as plt
data=pd.read_csv("property_data.csv")
avg=data.groupby("Location")["ListingPrice"].mean()
count=(data["Bedrooms"]>4).sum()
largest=data.loc[data["Area"].idxmax()]
print(avg)
print(count)
print(largest)
avg.plot(kind="bar")
plt.title("Average Listing Price")
plt.xlabel("Location")
plt.ylabel("Price")
plt.show()
plt.figure(figsize=(6,4))
plt.scatter(data["Area"],data["ListingPrice"])
plt.title("Area vs Listing Price")
plt.xlabel("Area")
plt.ylabel("Listing Price")
plt.grid(True)
plt.show()