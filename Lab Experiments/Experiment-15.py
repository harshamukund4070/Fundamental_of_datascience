import pandas as pd
import matplotlib.pyplot as plt
data=pd.read_csv("city_temperature.csv")
mean_temp=data.groupby("City")["Temperature"].mean()
std_temp=data.groupby("City")["Temperature"].std()
temp_range=data.groupby("City")["Temperature"].apply(lambda x:x.max()-x.min())
highest_range=temp_range.idxmax()
most_consistent=std_temp.idxmin()
print(mean_temp)
print(std_temp)
print(highest_range)
print(most_consistent)
mean_temp.plot(kind="bar")
plt.title("Mean Temperature by City")
plt.xlabel("City")
plt.ylabel("Mean Temperature")
plt.show()
temp_range.plot(kind="bar")
plt.title("Temperature Range by City")
plt.xlabel("City")
plt.ylabel("Range")
plt.show()